CREATE TABLE loans (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES library_users (id),
    book_copy_id BIGINT      NOT NULL REFERENCES book_copies (id),
    borrowed_at  TIMESTAMPTZ NOT NULL,
    due_at       TIMESTAMPTZ NOT NULL,
    returned_at  TIMESTAMPTZ,
    CONSTRAINT ck_loans_due_after_borrow CHECK (due_at > borrowed_at),
    CONSTRAINT ck_loans_return_after_borrow CHECK (returned_at IS NULL OR returned_at >= borrowed_at)
);

-- Garante no próprio banco, mesmo sob concorrência, um único empréstimo ativo por exemplar.
CREATE UNIQUE INDEX uk_loans_active_copy ON loans (book_copy_id) WHERE returned_at IS NULL;
CREATE INDEX ix_loans_active_due ON loans (due_at) WHERE returned_at IS NULL;
CREATE INDEX ix_loans_user_borrowed ON loans (user_id, borrowed_at DESC);
CREATE INDEX ix_loans_copy ON loans (book_copy_id);

CREATE TABLE reservations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES library_users (id),
    book_id      BIGINT      NOT NULL REFERENCES books (id),
    book_copy_id BIGINT REFERENCES book_copies (id),
    status       VARCHAR(20) NOT NULL DEFAULT 'WAITING',
    created_at   TIMESTAMPTZ NOT NULL,
    ready_until  TIMESTAMPTZ,
    CONSTRAINT ck_reservations_status
        CHECK (status IN ('WAITING', 'READY', 'FULFILLED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_reservations_ready_data
        CHECK (status <> 'READY' OR (book_copy_id IS NOT NULL AND ready_until IS NOT NULL))
);

-- Cada usuário tem no máximo uma reserva aberta por livro, e cada exemplar atende uma reserva por vez.
CREATE UNIQUE INDEX uk_reservations_open_user_book ON reservations (user_id, book_id)
    WHERE status IN ('WAITING', 'READY');
CREATE UNIQUE INDEX uk_reservations_ready_copy ON reservations (book_copy_id) WHERE status = 'READY';
-- Fila FIFO: a ordem vem de created_at e id, sem coluna de posição.
CREATE INDEX ix_reservations_queue ON reservations (book_id, created_at, id) WHERE status = 'WAITING';
CREATE INDEX ix_reservations_expiry ON reservations (ready_until) WHERE status = 'READY';
CREATE INDEX ix_reservations_user ON reservations (user_id, created_at DESC);

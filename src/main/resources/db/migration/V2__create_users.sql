CREATE TABLE library_users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(150) NOT NULL,
    normalized_email VARCHAR(254) NOT NULL,
    password_hash    VARCHAR(100) NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_library_users_email UNIQUE (normalized_email),
    CONSTRAINT ck_library_users_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE roles (
    name VARCHAR(30) PRIMARY KEY
);

INSERT INTO roles (name) VALUES ('ROLE_MEMBER'), ('ROLE_LIBRARIAN');

CREATE TABLE user_roles (
    user_id   BIGINT      NOT NULL REFERENCES library_users (id) ON DELETE CASCADE,
    role_name VARCHAR(30) NOT NULL REFERENCES roles (name),
    PRIMARY KEY (user_id, role_name)
);

CREATE TABLE refresh_sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES library_users (id) ON DELETE CASCADE,
    -- Somente o hash SHA-256 do token é guardado.
    token_hash  VARCHAR(64) NOT NULL,
    issued_at   TIMESTAMPTZ NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ,
    replaced_by BIGINT REFERENCES refresh_sessions (id),
    CONSTRAINT uk_refresh_sessions_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_refresh_sessions_active_user ON refresh_sessions (user_id) WHERE revoked_at IS NULL;
